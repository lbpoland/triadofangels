// Convert your existing albums array into the normalized format expected by render.js.
const normalizedAlbums = (albums || []).map((a) => {
  // Ensure genre is an array
  const genreList = Array.isArray(a.genre)
    ? a.genre
    : typeof a.genre === "string"
    ? a.genre.split(",").map((g) => g.trim())
    : [];

  // Convert track strings into objects with ids, pulling details from the lyrics section if present
  const tracksList = (a.tracks || []).map((name) => {
    const id = name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");
    const lyricEntry = a.lyrics && a.lyrics[id] ? a.lyrics[id] : {};
    const links = lyricEntry.links || {};
    return {
      id: id,
      title: name,
      duration: lyricEntry.duration || "",
      feat: lyricEntry.feat || "",
      lyrics: lyricEntry.file || "",
      spotify: links.spotify || "",
      apple: links.appleMusic || "",
      youtubeMusic: links.youTubeMusic || "",
      albumId: a.id,
    };
  });

  // Map artist names to keys used in the header
  const artistKey =
    a.artist && a.artist.toLowerCase().includes("triad")
      ? "triadOfAngels"
      : "toaStudios";

  return {
    id: a.id,
    artist: artistKey,
    title: a.title,
    year: a.year || "",
    genre: genreList,
    cover: a.cover.startsWith("/") ? a.cover : "/" + a.cover,
    spotify: (a.links || {}).spotify || "",
    apple: (a.links || {}).appleMusic || "",
    youtubeMusic: (a.links || {}).youTubeMusic || "",
    tracks: tracksList,
  };
});

